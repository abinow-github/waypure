import { chromium } from 'playwright';
import { mkdir, readFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
await mkdir('test-results', { recursive: true });
const browser = await chromium.launch({ channel: 'chrome', headless: true, args: process.env.SOFTWARE_GL === '1' ? ['--enable-webgl', '--use-angle=swiftshader'] : ['--enable-webgl'] });
const errors = [];
const page = await browser.newPage({ viewport: { width: 1440, height: 960 }, deviceScaleFactor: 1 });
page.on('pageerror', error => errors.push(error.message));
page.on('response', response => { if (response.status() >= 400) errors.push(`${response.status()} ${response.url()}`); });
const base = process.env.TEST_URL || 'http://127.0.0.1:3000';
try {
await page.goto(base, { waitUntil: 'networkidle' });
await page.locator('.scene-wrap.is-rendered').waitFor({ timeout: 30000 });
await page.waitForTimeout(1500);
assert.equal(await page.evaluate(() => typeof window.gsap), 'object', 'GSAP is loaded');
assert.equal(await page.evaluate(() => typeof window.ScrollTrigger), 'function', 'ScrollTrigger is loaded');
assert(Number(await page.locator('h1').evaluate(el=>getComputedStyle(el).opacity)) >= .8, 'Hero heading remains readable during entrance');
await page.screenshot({ path: 'test-results/desktop-hero.png' });
const initialFill = Number(await page.locator('#product-canvas').getAttribute('data-tank-fill'));
async function stage(progress) {
  await page.evaluate(p => { document.documentElement.style.scrollBehavior = 'auto'; const el = document.querySelector('.experience'); window.scrollTo(0, (el.offsetHeight - innerHeight) * p); }, progress);
  await page.waitForFunction(p => { const bar = document.querySelector('.scroll-progress span'); return Math.abs(parseFloat(bar.style.width) / 100 - p) < .004; }, progress, { timeout: 30000 });
  await page.waitForTimeout(500);
}
await stage(.36);
const fullTank = Number(await page.locator('#product-canvas').getAttribute('data-tank-fill'));
assert(fullTank > initialFill + .6, 'Purifier fills as the page scrolls');
await page.screenshot({ path: 'test-results/desktop-fill.png' });
await stage(.66);
assert.equal(await page.locator('#product-canvas').getAttribute('data-pouring'), 'true');
assert.equal(await page.locator('.experience-sticky').evaluate(el=>getComputedStyle(el).getPropertyValue('--scene-ink').trim()), '#f1f9ff', 'Pouring stage uses white text');
await page.screenshot({ path: 'test-results/desktop-pour.png' });
await stage(.96);
const fullGlass = Number(await page.locator('#product-canvas').getAttribute('data-glass-fill'));
assert(fullGlass > .95, 'Glass fills near the end of the journey');
assert.equal(await page.locator('#product-canvas').getAttribute('data-pouring'), 'false');
await page.screenshot({ path: 'test-results/desktop-glass.png' });
await stage(0);
assert(Number(await page.locator('#product-canvas').getAttribute('data-glass-fill')) < .01, 'Water animation reverses on scroll');
await page.locator('.nav-cta').click();
await page.waitForTimeout(900);
await page.locator('.product-copy .enquire-button').click();
assert(await page.locator('#enquiry-dialog').isVisible());
await page.locator('input[name=name]').fill('Test Customer');
await page.locator('input[name=email]').fill('test@example.com');
await page.locator('input[name=city]').fill('Kochi');
await page.locator('textarea[name=message]').fill('Please share pricing and capacity.');
await page.locator('#enquiry-form button[type=submit]').click();
assert(await page.locator('#enquiry-success').isVisible());
const [download] = await Promise.all([page.waitForEvent('download'), page.locator('#download-enquiry').click()]);
await download.saveAs('test-results/enquiry.txt');
assert((await readFile('test-results/enquiry.txt','utf8')).includes('Kochi'));
await page.locator('#edit-enquiry').click();
assert.equal(await page.locator('input[name=name]').inputValue(), 'Test Customer');
await page.keyboard.press('Escape');
assert.equal(await page.locator('#enquiry-dialog').isVisible(), false);
await page.locator('.faq-list summary').first().click();
assert.equal(await page.locator('.faq-list details').first().getAttribute('open'), '');
await page.locator('#difference').scrollIntoViewIfNeeded();
await page.waitForTimeout(800);
await page.screenshot({ path: 'test-results/desktop-difference.png' });
await page.locator('#details').scrollIntoViewIfNeeded();
await page.waitForTimeout(800);
await page.screenshot({ path: 'test-results/desktop-product.png' });
assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, 'No desktop overflow');
await page.setViewportSize({width:390,height:844});
await stage(0);
await page.screenshot({ path:'test-results/mobile-hero.png' });
assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, 'No mobile overflow');
await page.locator('.menu-toggle').click();
assert(await page.locator('#mobile-nav').isVisible());
await page.locator('#mobile-nav a[href="#difference"]').click();
assert.equal(await page.locator('#mobile-nav').isVisible(),false);
await stage(.66);
await page.screenshot({path:'test-results/mobile-pour.png'});
await page.emulateMedia({reducedMotion:'reduce'});
await stage(0);
assert.equal(await page.locator('.experience').evaluate(el=>Math.round(el.offsetHeight)),844);
assert.equal(await page.locator('#product-canvas').getAttribute('data-pouring'),'false');
await page.screenshot({path:'test-results/mobile-reduced-motion.png'});
for (const width of [320, 768, 1024]) {
  await page.setViewportSize({width,height:800});
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, `No overflow at ${width}px`);
}
const fallback = await browser.newPage({viewport:{width:1280,height:800}});
await fallback.route('**/scene.js',route=>route.abort());
await fallback.goto(base,{waitUntil:'networkidle'});
assert(await fallback.locator('.scene-wrap.is-fallback').isVisible());
assert.equal(await fallback.locator('.product-fallback').evaluate(el=>getComputedStyle(el).opacity),'1');
await fallback.close();
assert.deepEqual(errors, [], 'No JavaScript or asset loading errors');
console.log('PASS: 3D rendering, tank filling, pouring, glass filling, reverse scroll, desktop/mobile layout (320–1440px), navigation, enquiry download, FAQ, reduced motion, and static fallback.');
} finally { await browser.close(); }
